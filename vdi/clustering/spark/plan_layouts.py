"""Enumerate every sorting configuration in the sweep and the distinct layouts it needs.

A configuration is (value assignment, strategy, k tables, c sort columns). A layout is
one (table, sort columns) pair. Because rankings are prefixes, configurations share
layouts heavily; each layout is built and measured once, and a configuration's bytes are
reconstructed by adding per-table savings (validated in the `validate` phase).

All rankings use the multi-row-group filter (REVISION_SORTING.md): only tables spanning
more than one 128k-row row group are candidates.

Output: manifest.json (committed; the node treats it as the source of truth).
"""
import json
import sys
from argparse import ArgumentParser
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
from rank import rank, multi_rowgroup_tables  # noqa: E402

from workload import P  # noqa: E402  (WORKLOAD=tpcds by default; see workload.py)

COLUMNS_IN_QUERIES = P["columns_in_queries"]

# TPC-DS: "0".."4" = Constant, Value 50, 100, 500, 1000. IMDb: see make_harness_inputs.py.
VALUE_ITERS = P["value_iters"]
VALUE_NAMES = P["value_names"]
STRATEGIES = ["value", "frequency", "random"]
K_SWEEP = P["k_sweep"]        # at C_FIXED; TPC-DS: 10 = number of multi-row-group tables
C_FIXED = 2
C_SWEEP = [1, 2, 3]           # at K_FIXED
K_FIXED = 2

# Full configurations run directly to check that per-table savings add up.
VALIDATE = [tuple(v) for v in P["validate"]]

# Pilot: one strategy's top table and columns. TPC-DS: Frequent's store_sales
# (ss_sold_date_sk, ss_item_sk).
PILOT_STRATEGY = P["pilot"]["strategy"]
PILOT_ITER = P["pilot"]["value_iter"]
PILOT_TABLE = P["pilot"]["table"]


def main():
    parser = ArgumentParser()
    parser.add_argument("--out", default=str(P["manifest"]))
    parser.add_argument("--keep-ids-from", help="earlier manifest: layouts it lists keep their "
                        "ids (built tables are named by id); others get new ids after its last")
    args = parser.parse_args()

    eligible = sorted(multi_rowgroup_tables())
    assert len(eligible) == P["expect_eligible"] and max(K_SWEEP) <= len(eligible), eligible

    grid = sorted({(i, s, k, C_FIXED) for i in VALUE_ITERS for s in STRATEGIES for k in K_SWEEP} |
                  {(i, s, K_FIXED, c) for i in VALUE_ITERS for s in STRATEGIES for c in C_SWEEP},
                  key=lambda x: (x[0], STRATEGIES.index(x[1]), x[2], x[3]))

    layouts = {}      # (table, cols) -> id
    configs = []
    for (i, s, k, c) in grid:
        tables = rank(i, k, c, multi_rowgroup_only=True)[s]
        assert len(tables) == k and all(len(v) == c for v in tables.values())
        ids = {}
        for t, cols in tables.items():
            key = (t, tuple(cols))
            if key not in layouts:
                layouts[key] = None
            ids[t] = key
        configs.append({"value_iter": i, "value_name": VALUE_NAMES[i], "strategy": s,
                        "k": k, "c": c, "tables": tables, "_keys": ids})

    if args.keep_ids_from:
        old = {(v["table"], tuple(v["sort_cols"])): lid
               for lid, v in json.load(open(args.keep_ids_from))["layouts"].items()}
        nxt = max((int(lid[1:]) for lid in old.values()), default=-1) + 1
        for key in sorted(layouts):
            if key in old:
                layouts[key] = old[key]
            else:
                layouts[key] = f"l{nxt:03d}"; nxt += 1
    else:
        for n, key in enumerate(sorted(layouts)):
            layouts[key] = f"l{n:03d}"
    for cfg in configs:
        cfg["layouts"] = {t: layouts[key] for t, key in cfg.pop("_keys").items()}
        cfg["id"] = f"v{cfg['value_iter']}_{cfg['strategy']}_k{cfg['k']}_c{cfg['c']}"

    cols_in_q = json.load(open(COLUMNS_IN_QUERIES))
    queries_by_table = {t: sorted(q.split(".")[0] for q, tbls in cols_in_q.items()
                                  if tbls.get(t))
                        for t in eligible}

    validate_ids = [f"v{i}_{s}_k{k}_c{c}" for (i, s, k, c) in VALIDATE]
    assert all(v in {c["id"] for c in configs} for v in validate_ids)

    pilot_cols = rank(PILOT_ITER, 1, 2, multi_rowgroup_only=True)[PILOT_STRATEGY][PILOT_TABLE]
    pilot_layout = layouts[(PILOT_TABLE, tuple(pilot_cols))]

    manifest = {
        "note": "Generated by plan_layouts.py; see REVISION_SORTING.md.",
        "params": {"value_iters": VALUE_ITERS, "strategies": STRATEGIES,
                   "k_sweep": K_SWEEP, "c_fixed": C_FIXED, "c_sweep": C_SWEEP,
                   "k_fixed": K_FIXED, "multi_rowgroup_only": True,
                   "eligible_tables": eligible},
        "layouts": {lid: {"table": t, "sort_cols": list(cols)}
                    for (t, cols), lid in sorted(layouts.items(), key=lambda x: x[1])},
        "configs": configs,
        "queries_by_table": queries_by_table,
        "validate": validate_ids,
        "pilot": {"table": PILOT_TABLE, "layout": pilot_layout,
                  "sort_cols": pilot_cols, "modes": ["s", "ps", "pz"],
                  "queries": queries_by_table[PILOT_TABLE]},
    }
    with open(args.out, "w") as f:
        json.dump(manifest, f, indent=2)

    runs = sum(len(queries_by_table[v["table"]]) for v in manifest["layouts"].values())
    print(f"{len(configs)} configurations, {len(layouts)} distinct layouts, "
          f"{runs} per-layout query runs (+{len(P['queries'])} baseline)")
    print(f"pilot: {PILOT_TABLE} {pilot_cols} -> {pilot_layout}, "
          f"{len(manifest['pilot']['queries'])} queries")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
